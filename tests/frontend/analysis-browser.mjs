  const report = await page.fetch(artifact);
  assert(report.ok && report.body.indexOf('<dl class="overview-metrics">') < report.body.indexOf('id="story"'), 'report is not overview-first');
  assert(report.body.includes('待确认与下一步') && !report.body.includes('来源：message_'), 'report followups/source disclosure missing');
