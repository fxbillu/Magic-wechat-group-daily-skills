  await page.waitForSelector("input[name=q]");
  if (width === 1280) console.log(await page.snapshot());
  await page.fill("input[name=q]", "对账问题");
  await page.selectOption("select[name=chat]", input.group);
  await page.fill("input[name=from]", input.day);
  await page.fill("input[name=to]", input.day);
  await page.fill("input[name=sender]", "wxid_alpha");
  await page.click("button[type=submit]");
  await page.waitForSelector(".search-context");
  assert(await page.evaluate(() => document.querySelectorAll(".hit-text").length === 2), "person/topic filters lost matches");
  await page.click(".search-context summary >> nth=0");
  await page.waitForSelector(".context-match");
  assert(await page.evaluate(() => document.querySelectorAll(".context-message").length === 21), "wrong context window");
  assert(await page.evaluate(() => document.querySelectorAll(".context-match").length === 1), "anchor not unique");
  assert(await page.evaluate(() => document.querySelector(".search-context").innerText.includes("继续核对。")), "filtered-out replies missing");
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "search page overflow");
  await page.screenshot({path:input.evidence + "/context-" + width + ".png"});
  await page.reload();
  await page.waitForSelector(".hit-text");
  assert(await page.evaluate(() => document.querySelector("input[name=sender]").value === "wxid_alpha"), "person filter lost on reload");
  await page.click(".hit-actions a >> nth=0");
  await page.waitForSelector(".analysis-panel");
  await page.waitForSelector(".reader-metrics");
  assert(await page.evaluate(() => !document.querySelector('.reader-activity').open), 'full activity table must start collapsed');
  assert(await page.evaluate(() => document.querySelector('.reader-metrics').innerText.includes('30') && document.querySelector('.reader-metrics').innerText.includes('2')), 'overview metrics missing');
  assert(await page.evaluate(() => document.querySelector('.reader-followups').innerText.includes('确认对账结果')), 'followup overview missing');
